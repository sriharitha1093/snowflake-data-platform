create or replace view VW_PAYMENTS(
	PAYMENT_ID,
	ORDER_ID,
	PAYMENT_DATE,
	PAYMENT_AMOUNT,
	PAYMENT_METHOD,
	PAYMENT_CATEGORY
) as
SELECT
    PAYMENT_ID,
    ORDER_ID,
    PAYMENT_DATE,
    PAYMENT_AMOUNT,
    PAYMENT_METHOD,
    CASE
        WHEN PAYMENT_AMOUNT >= 1000 THEN 'HIGH VALUE'
        ELSE 'NORMAL VALUE'
    END AS PAYMENT_CATEGORY
FROM PAYMENTS;
