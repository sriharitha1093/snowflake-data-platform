create or replace view VW_PRODUCTS(
	PRODUCT_ID,
	PRODUCT_NAME,
	CATEGORY,
	PRICE,
	PRICE_CATEGORY
) as
SELECT
    PRODUCT_ID,
    PRODUCT_NAME,
    CATEGORY,
    PRICE,
    CASE
        WHEN PRICE >= 700 THEN 'EXPENSIVE'
        WHEN PRICE >= 300 THEN 'MODERATE'
        ELSE 'AFFORDABLE'
    END AS PRICE_CATEGORY
FROM PRODUCTS;
