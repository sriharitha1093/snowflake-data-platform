create or replace view VW_EMPLOYEES(
	EMPLOYEE_ID,
	EMPLOYEE_NAME,
	DEPARTMENT,
	SALARY,
	HIRE_DATE,
	SALARY_CATEGORY
) as
SELECT
    EMPLOYEE_ID,
    EMPLOYEE_NAME,
    DEPARTMENT,
    SALARY,
    HIRE_DATE,
    CASE
        WHEN SALARY >= 80000 THEN 'SENIOR SALARY BAND'
        WHEN SALARY >= 50000 THEN 'MID SALARY BAND'
        ELSE 'ENTRY SALARY BAND'
    END AS SALARY_CATEGORY
FROM EMPLOYEES;
