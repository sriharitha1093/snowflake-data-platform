create or replace view VW_ORDERS(
	ORDER_ID,
	CUSTOMER_ID,
	ORDER_DATE,
	ORDER_AMOUNT,
	ORDER_STATUS,
	ORDER_YEAR,
	ORDER_MONTH
) as
SELECT
    ORDER_ID,
    CUSTOMER_ID,
    ORDER_DATE,
    ORDER_AMOUNT,
    ORDER_STATUS,
    YEAR(ORDER_DATE) AS ORDER_YEAR,
    MONTH(ORDER_DATE) AS ORDER_MONTH
FROM ORDERS;
